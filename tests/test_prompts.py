import pytest

from conpo.data import PoolRow, load_pool
from conpo.prompts import counterfactual_prompts, prompt_with_only

_SAMPLE_LIMIT = 500


@pytest.fixture(scope="module")
def multi_sentence_row() -> PoolRow:
    rows, _ = load_pool(limit=_SAMPLE_LIMIT)
    return next(r for r in rows if len(r.sentences) >= 2)


def test_counterfactual_prompts_removes_target_only(multi_sentence_row: PoolRow) -> None:
    row = multi_sentence_row

    x_plus, x_minus = counterfactual_prompts(row, 0)
    assert x_plus == row.prompt
    assert row.sentences[0] not in x_minus
    for sentence in row.sentences[1:]:
        assert sentence in x_minus

    # every character outside the deletion seam is byte-identical
    idx = row.prompt.index(row.sentences[0])
    tail_plus = row.prompt[idx + len(row.sentences[0]) :]
    tail_minus = x_minus[idx:]
    assert tail_plus.lstrip(" ") == tail_minus.lstrip(" ")
    assert row.prompt[:idx].rstrip(" ") == x_minus[:idx].rstrip(" ")


def test_counterfactual_prompts_last_sentence_leaves_no_trailing_space(multi_sentence_row: PoolRow) -> None:
    row = multi_sentence_row
    last = len(row.sentences) - 1

    _, x_minus = counterfactual_prompts(row, last)
    assert row.sentences[last] not in x_minus
    assert not x_minus.endswith(" ")
    for sentence in row.sentences[:last]:
        assert sentence in x_minus


def test_counterfactual_prompts_raises_when_sentence_missing() -> None:
    row = PoolRow(
        key="k",
        base_prompt="base",
        prompt="base tail",
        sentences=("not present verbatim",),
        constraints=(),
        english=True,
        num_constraints=0,
    )
    with pytest.raises(ValueError):
        counterfactual_prompts(row, 0)


def test_counterfactual_prompts_targets_correct_occurrence_of_duplicate_sentence() -> None:
    # Two sentences with identical text (e.g. two rows generated by different
    # instruction ids that happen to render the same requirement sentence)
    # must not both be treated as one leftmost match: deleting the second
    # occurrence must remove the SECOND occurrence, not the first.
    dup = "There should be 2 paragraphs."
    sentences = (dup, "Use exactly 3 bullet points.", dup)
    prompt = f"Do the task. {dup} {sentences[1]} {dup}"
    row = PoolRow(
        key="k",
        base_prompt="Do the task.",
        prompt=prompt,
        sentences=sentences,
        constraints=(),
        english=True,
        num_constraints=len(sentences),
    )

    _, x_minus = counterfactual_prompts(row, 2)
    # the second occurrence (index 2) is gone...
    assert x_minus.count(dup) == 1
    # ...but the first occurrence (index 0) and the untouched middle sentence remain
    assert x_minus.startswith(row.base_prompt)
    assert dup in x_minus
    assert sentences[1] in x_minus
    assert x_minus == f"{row.base_prompt} {dup} {sentences[1]}"


def test_prompt_with_only_selects_given_sentences(multi_sentence_row: PoolRow) -> None:
    row = multi_sentence_row

    only_first = prompt_with_only(row, [0])
    assert only_first == f"{row.base_prompt} {row.sentences[0]}"

    all_sentences = prompt_with_only(row, list(range(len(row.sentences))))
    assert all_sentences == f"{row.base_prompt} {' '.join(row.sentences)}"
    assert all_sentences.startswith(row.base_prompt)
    for sentence in row.sentences:
        assert sentence in all_sentences

    none_selected = prompt_with_only(row, [])
    assert none_selected == row.base_prompt


